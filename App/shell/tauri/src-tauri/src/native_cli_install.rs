//! Install the actual bundled memmy-memory Node CLI launcher into ~/.local/bin.
//! Never executes renderer input. Refuses to overwrite unrelated executables.
use serde::Serialize;
use std::{
    fs::{self, OpenOptions},
    io::Write,
    path::{Path, PathBuf},
};
use tauri::{AppHandle, Manager, WebviewWindow};
const MARKER: &str = "# Generated by Memmy Turbo Tauri native CLI installer - do not edit";
const PATH_MARKER: &str = "# Memmy CLI PATH";
const PATH_LINE: &str = "export PATH=\"$HOME/.local/bin:$PATH\"";
const MAX_PROFILE_BYTES: u64 = 1024 * 1024;

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct InstalledCli {
    name: String,
    source: String,
    target: String,
}
#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CliInstallResult {
    ok: bool,
    bin_directory: String,
    installed: Vec<InstalledCli>,
    path_updated: bool,
    profile_paths: Vec<String>,
}

fn safe_regular(path: &Path) -> Result<(), String> {
    let meta = fs::symlink_metadata(path).map_err(|_| "CLI runtime component unavailable")?;
    if !meta.is_file() || meta.file_type().is_symlink() {
        return Err("CLI runtime component must be a regular file".into());
    }
    Ok(())
}
fn safe_folder(path: &Path) -> Result<(), String> {
    let meta = fs::symlink_metadata(path).map_err(|_| "CLI folder cannot be inspected")?;
    if !meta.is_dir() || meta.file_type().is_symlink() {
        return Err("CLI folder must not be a symlink".into());
    }
    Ok(())
}
fn quote_shell(path: &Path) -> Result<String, String> {
    let raw = path.to_str().ok_or("CLI path is not valid UTF-8")?;
    if raw.is_empty() || raw.chars().any(char::is_control) {
        return Err("CLI runtime path contains control characters".into());
    }
    Ok(format!("'{}'", raw.replace('\'', "'\\''")))
}
fn validate_components(node: &Path, cli: &Path) -> Result<(), String> {
    if !node.is_absolute() || !cli.is_absolute() || cli.file_name().is_none_or(|n| n != "index.js")
    {
        return Err("CLI components must be absolute bundled paths".into());
    }
    safe_regular(node)?;
    safe_regular(cli)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        if fs::metadata(node)
            .map_err(|_| "Node executable unavailable")?
            .permissions()
            .mode()
            & 0o111
            == 0
        {
            return Err("bundled Node runtime is not executable".into());
        }
    }
    Ok(())
}
fn launcher(node: &Path, cli: &Path) -> Result<String, String> {
    validate_components(node, cli)?;
    Ok(format!(
        "#!/bin/sh\n{MARKER}\nexec {} {} \"$@\"\n",
        quote_shell(node)?,
        quote_shell(cli)?
    ))
}
fn create_dir_safely(home: &Path, name: &str) -> Result<PathBuf, String> {
    safe_folder(home)?;
    let path = home.join(name);
    if !path.exists() {
        fs::create_dir(&path).map_err(|_| "cannot create CLI folder")?;
    }
    safe_folder(&path)?;
    Ok(path)
}
fn ensure_launcher(target: &Path, data: &str) -> Result<(), String> {
    let parent = target.parent().ok_or("CLI target has no parent")?;
    safe_folder(parent)?;
    match fs::symlink_metadata(target) {
        Ok(meta) => {
            if !meta.is_file() || meta.file_type().is_symlink() || meta.len() > 16384 {
                return Err("existing CLI target is not a trusted launcher".into());
            }
            let current =
                fs::read_to_string(target).map_err(|_| "existing CLI launcher is unreadable")?;
            if !current.lines().any(|line| line == MARKER) {
                return Err("refusing to replace unrelated existing memmy-memory command".into());
            }
            if current == data {
                return Ok(());
            }
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
        Err(_) => return Err("cannot inspect CLI target".into()),
    };
    let temporary = parent.join(format!(".memmy-cli-{}.tmp", uuid::Uuid::new_v4()));
    let mut options = OpenOptions::new();
    options.create_new(true).write(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o700);
    }
    let mut file = options
        .open(&temporary)
        .map_err(|_| "cannot stage CLI launcher")?;
    let result = file
        .write_all(data.as_bytes())
        .and_then(|_| file.sync_all())
        .and_then(|_| fs::rename(&temporary, target));
    let _ = fs::remove_file(&temporary);
    result.map_err(|_| "cannot install CLI launcher".into())
}
fn preflight_profile(path: &Path) -> Result<(), String> {
    match fs::symlink_metadata(path) {
        Ok(meta) => {
            if !meta.is_file() || meta.file_type().is_symlink() || meta.len() > MAX_PROFILE_BYTES {
                return Err("shell profile unsafe; refusing to modify".into());
            }
            fs::read_to_string(path).map_err(|_| "cannot read shell profile")?;
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(_) => return Err("cannot inspect shell profile".into()),
    }
    Ok(())
}
fn ensure_profile(path: &Path) -> Result<bool, String> {
    let current = match fs::symlink_metadata(path) {
        Ok(meta) => {
            if !meta.is_file() || meta.file_type().is_symlink() || meta.len() > MAX_PROFILE_BYTES {
                return Err("shell profile unsafe; refusing to modify".into());
            }
            fs::read_to_string(path).map_err(|_| "cannot read shell profile")?
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => String::new(),
        Err(_) => return Err("cannot inspect shell profile".into()),
    };
    if current.lines().any(|line| line.trim() == PATH_LINE) {
        return Ok(false);
    }
    // Preserve all existing user settings and only append the fixed, idempotent line.
    let mut updated = current.clone();
    if !updated.is_empty() && !updated.ends_with('\n') {
        updated.push('\n');
    }
    updated.push_str(PATH_MARKER);
    updated.push('\n');
    updated.push_str(PATH_LINE);
    updated.push('\n');
    let parent = path.parent().ok_or("shell profile missing parent")?;
    safe_folder(parent)?;
    let temporary = parent.join(format!(".memmy-profile-{}.tmp", uuid::Uuid::new_v4()));
    let mut options = OpenOptions::new();
    options.create_new(true).write(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    let mut handle = options
        .open(&temporary)
        .map_err(|_| "cannot stage shell profile")?;
    let result = handle
        .write_all(updated.as_bytes())
        .and_then(|_| handle.sync_all())
        .and_then(|_| fs::rename(&temporary, path));
    let _ = fs::remove_file(&temporary);
    result.map_err(|_| "cannot update shell profile".to_string())?;
    Ok(true)
}
fn install(home: &Path, node: &Path, cli: &Path) -> Result<CliInstallResult, String> {
    let contents = launcher(node, cli)?;
    let local = create_dir_safely(home, ".local")?;
    let bin = create_dir_safely(&local, "bin")?;
    // Validate BOTH user shell profiles before modifying either profile
    // or writing a CLI executable; unsafe profiles leave installation untouched.
    for file in [".zshrc", ".bash_profile"] {
        preflight_profile(&home.join(file))?;
    }
    let target = bin.join("memmy-memory");
    ensure_launcher(&target, &contents)?;
    let mut profiles = Vec::new();
    for file in [".zshrc", ".bash_profile"] {
        let p = home.join(file);
        if ensure_profile(&p)? {
            profiles.push(p.to_string_lossy().into_owned());
        }
    }
    Ok(CliInstallResult {
        ok: true,
        bin_directory: bin.to_string_lossy().into_owned(),
        installed: vec![InstalledCli {
            name: "memmy-memory".into(),
            source: cli.to_string_lossy().into_owned(),
            target: target.to_string_lossy().into_owned(),
        }],
        path_updated: !profiles.is_empty(),
        profile_paths: profiles,
    })
}
fn installed_sources(resources: &Path) -> Result<(PathBuf, PathBuf), String> {
    let runtime = resources.join("runtime");
    safe_folder(&runtime)?;
    let node = runtime.join(if cfg!(windows) { "node.exe" } else { "node" });
    let cli = runtime.join("Memory/dist/src/cli/index.js");
    validate_components(&node, &cli)?;
    Ok((node, cli))
}
#[tauri::command]
pub async fn desktop_install_cli_tools(
    app: AppHandle,
    window: WebviewWindow,
) -> Result<CliInstallResult, String> {
    if window.label() != "main" {
        return Err("CLI installation requires first-party main window".into());
    }
    if cfg!(windows) {
        return Err(
            "native Windows CLI installer requires signed .cmd artifacts and PATH registration"
                .into(),
        );
    }
    let home = app.path().home_dir().map_err(|_| "home path unavailable")?;
    let resources = app
        .path()
        .resource_dir()
        .map_err(|_| "packaged runtime resource directory unavailable")?;
    tauri::async_runtime::spawn_blocking(move || {
        let (node, cli) = installed_sources(&resources)?;
        install(&home, &node, &cli)
    })
    .await
    .map_err(|_| "CLI installation worker unavailable".to_string())?
}
#[cfg(test)]
mod tests {
    use super::*;
    #[cfg(unix)]
    use std::os::unix::fs::PermissionsExt;
    fn fixture() -> (PathBuf, PathBuf, PathBuf) {
        let root = std::env::temp_dir().join(format!("memmy-cli-test-{}", uuid::Uuid::new_v4()));
        fs::create_dir_all(root.join("home")).unwrap();
        fs::create_dir_all(root.join("runtime/Memory/dist/src/cli")).unwrap();
        let node = root.join("runtime/node");
        fs::write(&node, "#!/bin/sh\n").unwrap();
        #[cfg(unix)]
        fs::set_permissions(&node, fs::Permissions::from_mode(0o700)).unwrap();
        let cli = root.join("runtime/Memory/dist/src/cli/index.js");
        fs::write(&cli, "console.log('real CLI');").unwrap();
        (root, node, cli)
    }
    #[test]
    fn real_launcher_installation_is_idempotent_and_preserves_shell_settings() {
        let (root, node, cli) = fixture();
        let home = root.join("home");
        fs::write(home.join(".zshrc"), "export KEEP_ME=1\n").unwrap();
        let first = install(&home, &node, &cli).unwrap();
        assert!(first.ok);
        assert_eq!(first.installed.len(), 1);
        assert!(first.path_updated);
        let launcher = fs::read_to_string(home.join(".local/bin/memmy-memory")).unwrap();
        assert!(launcher.contains(&quote_shell(&node).unwrap()));
        assert!(launcher.contains(&quote_shell(&cli).unwrap()));
        let second = install(&home, &node, &cli).unwrap();
        assert!(!second.path_updated);
        assert!(second.profile_paths.is_empty());
        assert_eq!(
            fs::read_to_string(home.join(".zshrc"))
                .unwrap()
                .matches(PATH_LINE)
                .count(),
            1
        );
        assert!(fs::read_to_string(home.join(".zshrc"))
            .unwrap()
            .contains("KEEP_ME=1"));
        fs::remove_dir_all(root).unwrap();
    }
    #[test]
    fn refuses_unrelated_commands_and_symlinked_profiles_and_runtime() {
        let (root, node, cli) = fixture();
        let home = root.join("home");
        fs::create_dir_all(home.join(".local/bin")).unwrap();
        fs::write(
            home.join(".local/bin/memmy-memory"),
            "#!/bin/sh\nexec something-else\n",
        )
        .unwrap();
        assert!(install(&home, &node, &cli).is_err());
        fs::remove_file(home.join(".local/bin/memmy-memory")).unwrap();
        #[cfg(unix)]
        {
            std::os::unix::fs::symlink("/etc/hosts", home.join(".zshrc")).unwrap();
            assert!(install(&home, &node, &cli).is_err());
            assert!(!home.join(".local/bin/memmy-memory").exists());
            fs::remove_file(home.join(".zshrc")).unwrap();
            let temp = root.join("fake-node");
            std::os::unix::fs::symlink(&node, &temp).unwrap();
            assert!(launcher(&temp, &cli).is_err());
        }
        fs::remove_dir_all(root).unwrap();
    }
    #[test]
    #[cfg(unix)]
    fn packaged_wrapper_runs_real_bundled_node_without_shell_path_dependency() {
        let (root, node, cli) = fixture();
        fs::write(&node, "#!/bin/sh\nprintf '%s\\n' \"$1\" \"$2\"\n").unwrap();
        fs::set_permissions(&node, fs::Permissions::from_mode(0o700)).unwrap();
        let home = root.join("home");
        install(&home, &node, &cli).unwrap();
        let target = home.join(".local/bin/memmy-memory");
        let output = std::process::Command::new(&target)
            .arg("--version")
            .env("PATH", "/usr/bin:/bin")
            .output()
            .unwrap();
        assert!(output.status.success());
        let stdout = String::from_utf8(output.stdout).unwrap();
        assert_eq!(stdout, format!("{}\n--version\n", cli.display()));
        fs::remove_dir_all(root).unwrap();
    }
    #[test]
    fn safely_quotes_special_characters_in_runtime_absolute_paths() {
        let (root, _node, _cli) = fixture();
        let renamed = root.join("a' path");
        fs::rename(root.join("runtime"), &renamed).unwrap();
        let node = renamed.join("node");
        let cli = renamed.join("Memory/dist/src/cli/index.js");
        let text = launcher(&node, &cli).unwrap();
        assert!(text.contains("'\\''"));
        assert!(!text.contains("eval "));
        fs::remove_dir_all(root).unwrap();
    }
}
